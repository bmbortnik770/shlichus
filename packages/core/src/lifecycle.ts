export const lifeLabel = (type: string) => LIFE_TYPES.find((t) => t.key === type)?.label ?? type;

type Child = { name?: string; dob?: string; gender?: string; phone?: string; email?: string };
export interface LifeEvent { type: string; date: string; memberKey?: string; memberName?: string; notes?: string; autoTasks?: number }

/** בני המשפחה לבחירה: המשפחה, האב, האם והילדים (מפתחות כמו במערכת הקיימת) */
export function memberOptions(apt: Apartment): { key: string; label: string }[] {
  const out = [{ key: 'family', label: 'כל המשפחה' }];
  if (apt.father) out.push({ key: 'father', label: `האב · ${apt.father}` });
  if (apt.mother) out.push({ key: 'mother', label: `האם · ${apt.mother}` });
  for (const c of (apt.childrenList ?? []) as Child[]) if (c.name) out.push({ key: `child:${c.name}`, label: c.name });
  return out;
}

export function memberName(apt: Apartment, key: string | undefined): string {
  if (!key || key === 'family') return '';
  if (key === 'father') return apt.father || 'אבא';
  if (key === 'mother') return apt.mother || 'אמא';
  return key.startsWith('child:') ? key.slice(6) : key;
}

const iso = (d: Date) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
const atNoon = (s: string) => new Date(s.length === 10 ? `${s}T12:00:00` : s);
const startOfDay = (d: Date) => new Date(d.getFullYear(), d.getMonth(), d.getDate());

/** רישום אירוע חיים + משימות ההמשך שלו (מה שתאריכו עבר — מסומן כבוצע, כמו בישן) */
export function addLifeEvent(db: Db, ref: FamilyRef, ev: { type: string; date: string; memberKey?: string; notes?: string }, now = new Date()): number {
  const apt = getBuilding(db, ref.bldg)?.apts[ref.idx];
  if (!apt) return 0;
  const name = memberName(apt, ev.memberKey);
  const base = atNoon(ev.date);
  const today = startOfDay(now);
  const tasks: Task[] = (LIFE_TRIGGERS[ev.type] ?? []).map((tr) => {
    const d = new Date(base);
    d.setDate(d.getDate() + tr.offset);
    return { text: name ? `${tr.text} — ${name}` : tr.text, date: iso(d), done: d < today, member: ev.memberKey || 'family', autoGenerated: true, source: ev.type };
  });
  const rec: LifeEvent = { type: ev.type, date: ev.date, memberKey: ev.memberKey || 'family', memberName: name, notes: ev.notes ?? '', autoTasks: tasks.length };
  updateFamily(db, ref, {
    lifecycleEvents: [...((apt.lifecycleEvents ?? []) as LifeEvent[]), rec],
    tasks: [...((apt.tasks ?? []) as Task[]), ...tasks],
  });
  return tasks.length;
}

export function removeLifeEvent(db: Db, ref: FamilyRef, i: number): void {
  const apt = getBuilding(db, ref.bldg)?.apts[ref.idx];
  if (!apt) return;
  updateFamily(db, ref, { lifecycleEvents: ((apt.lifecycleEvents ?? []) as LifeEvent[]).filter((_, j) => j !== i) });
}

/** ימים עד יום השנה הבא של תאריך לועזי (0 = היום) */
export function daysUntilAnniversary(dateStr: string, now = new Date()): number | null {
  const d = atNoon(dateStr);
  if (Number.isNaN(d.getTime())) return null;
  const today = startOfDay(now);
  let next = new Date(today.getFullYear(), d.getMonth(), d.getDate());
  if (next < today) next = new Date(today.getFullYear() + 1, d.getMonth(), d.getDate());
  return Math.round((next.getTime() - today.getTime()) / 86400000);
}

export interface DateAlert { kind: 'birthday' | 'barmitzva' | 'life'; inDays: number; title: string }

/**
 * תזכורות מתאריכי לידה ואירועי חיים (כמו checkLifecycleAlerts):
 * יום הולדת לילד/הורה — 7 ימים; בר/בת מצווה (13/12) — 60 יום; יום שנה לאירוע חיים — 14 יום.
 */
export function dateAlerts(apt: Apartment, now = new Date()): DateAlert[] {
  const out: DateAlert[] = [];
  const today = startOfDay(now);
  for (const c of (apt.childrenList ?? []) as Child[]) {
    if (!c.name || !c.dob) continue;
    const bd = daysUntilAnniversary(c.dob, now);
    if (bd !== null && bd <= 7) out.push({ kind: 'birthday', inDays: bd, title: `יום הולדת ל${c.name}` });
    const girl = c.gender === 'girl' || c.gender === 'female' || c.gender === 'f';
    const dob = atNoon(c.dob);
    const bm = new Date(dob.getFullYear() + (girl ? 12 : 13), dob.getMonth(), dob.getDate());
    const diff = Math.round((startOfDay(bm).getTime() - today.getTime()) / 86400000);
    if (diff >= 0 && diff <= 60) out.push({ kind: 'barmitzva', inDays: diff, title: `${girl ? 'בת מצווה' : 'בר מצווה'} ל${c.name}` });
  }
  for (const [role, key] of [['father', 'fatherDob'], ['mother', 'motherDob']] as const) {
    const dob = apt[key] as string | undefined;
    const name = apt[role];
    if (!dob || !name) continue;
    const bd = daysUntilAnniversary(dob, now);
    if (bd !== null && bd <= 7) out.push({ kind: 'birthday', inDays: bd, title: `יום הולדת ל${name}` });
  }
  for (const ev of (apt.lifecycleEvents ?? []) as LifeEvent[]) {
    if (!ev.date || startOfDay(atNoon(ev.date)) >= today) continue; // האירוע עצמו — במשימות; כאן רק ימי שנה
    const d = daysUntilAnniversary(ev.date, now);
    if (d !== null && d <= 14) out.push({ kind: 'life', inDays: d, title: `יום שנה ל${lifeLabel(ev.type)}${ev.memberName ? ` (${ev.memberName})` : ''}` });
  }
  return out;
}
